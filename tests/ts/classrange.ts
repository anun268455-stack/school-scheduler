/**
 * ทดสอบ utils/classRange — ย่อรายชื่อห้องเรียนให้สั้นลงเป็นช่วง
 *
 *   "ตารางการใช้ห้องคือช่วยเขียนแบบสั้นๆ ไม่ต้องเอามาทั้งหมด เช่น 3/5-12
 *    รวมถึงตารางห้องที่ปริ้นออกมาด้วย"
 *
 * ห้องดนตรีไทยคาบหนึ่งมีสิบห้องเรียนเข้าใช้พร้อมกัน ของเดิมเขียนเรียงกันหมด
 * ทั้งบนจอและบนกระดาษ จนช่องเดียวสูงสิบบรรทัด
 *
 * ข้อที่สำคัญที่สุดของไฟล์นี้: ห้องเรียนต้องไม่หายไปเงียบ ๆ ป้ายที่อ่านไม่ออก
 * อย่าง "6ข" ต้องโผล่บนกระดาษเหมือนเดิม ไม่ใช่ถูกกลืนเพราะจับคู่รูปแบบไม่ได้
 */
import { classRanges } from "../../frontend/src/utils/classRange.ts";

let n = 0;
const ok = (cond: boolean, what: string): void => {
  n++;
  if (!cond) { console.error("FAIL:", what); process.exit(1); }
};
const eq = (a: unknown, b: unknown, what: string): void =>
  ok(JSON.stringify(a) === JSON.stringify(b), `${what} — ได้ ${JSON.stringify(a)}`);

// ── สิ่งที่ผู้ใช้ขอมาตรง ๆ ───────────────────────────────────────────────────
eq(classRanges(["3/5", "3/6", "3/7", "3/8", "3/9", "3/10", "3/11", "3/12"]),
   "3/5-12", "ต่อเนื่องกันทั้งหมด ยุบเหลือช่วงเดียว");

// ── กรณีพื้นฐาน ─────────────────────────────────────────────────────────────
eq(classRanges([]), "", "ไม่มีห้องเรียน = ว่าง");
eq(classRanges(["3/5"]), "3/5", "ห้องเดียวเขียนเหมือนเดิม");
eq(classRanges(["3/5", "3/6"]), "3/5-6", "สองห้องติดกันก็ยังเป็นช่วง");
eq(classRanges(["3/5", "3/7"]), "3/5,7", "ไม่ติดกัน คั่นด้วยจุลภาค");
eq(classRanges(["3/5", "3/5"]), "3/5", "ห้องซ้ำนับครั้งเดียว");

// ── ขาดช่วงกลาง ─────────────────────────────────────────────────────────────
eq(classRanges(["3/5", "3/6", "3/7", "3/8", "3/10"]), "3/5-8,10",
   "ช่วงหนึ่งแล้วตามด้วยห้องเดี่ยว");
eq(classRanges(["3/1", "3/2", "3/5", "3/6", "3/7"]), "3/1-2,5-7", "สองช่วง");

// ── คนละชั้น ────────────────────────────────────────────────────────────────
eq(classRanges(["3/5", "3/6", "6/1", "6/2", "6/3"]), "3/5-6 6/1-3",
   "คั่นระหว่างชั้นด้วยเว้นวรรค ไม่ใช่จุลภาค");
eq(classRanges(["6/1", "3/5"]), "3/5 6/1", "เรียงชั้นจากน้อยไปมาก ไม่ใช่ตามที่เจอ");

// ── เรียงเลขห้องแบบเลข ไม่ใช่แบบตัวอักษร ────────────────────────────────────
// เรียงแบบตัวอักษรจะได้ 1/10 มาก่อน 1/9 แล้วช่วงจะขาดเป็น "1/9-10" ไม่ได้
eq(classRanges(["1/9", "1/10", "1/11"]), "1/9-11", "เลขสองหลักต่อจากเลขหลักเดียว");
eq(classRanges(["1/14", "1/5", "1/6", "1/7", "1/8", "1/9", "1/10", "1/11", "1/12", "1/13"]),
   "1/5-14", "สิบห้องเรียนที่เข้ามาไม่เรียงลำดับ");

// ── ป้ายที่อ่านไม่ออกต้องไม่หาย ──────────────────────────────────────────────
// ห้องย่อย ก/ข/ค ที่เรียนพร้อมกันเขียนเป็น "6ข" ไม่มีเครื่องหมายทับ
eq(classRanges(["6ข", "6ค"]), "6ข 6ค", "อ่านไม่ออกก็เขียนตามเดิม");
eq(classRanges(["3/5", "3/6", "6ข"]), "3/5-6 6ข", "ปนกันได้ ของที่อ่านไม่ออกไปต่อท้าย");
eq(classRanges(["6ข", "3/5"]), "3/5 6ข", "ช่วงมาก่อนเสมอ แม้ของที่อ่านไม่ออกจะมาก่อน");
eq(classRanges(["6ข", "6ข"]), "6ข", "ของที่อ่านไม่ออกก็ไม่ซ้ำ");
eq(classRanges(["", "  ", "3/5"]), "3/5", "ป้ายว่างถูกทิ้ง ไม่กลายเป็นช่องว่างลอย");

// ── "ม." ที่หลุดมาด้วย ──────────────────────────────────────────────────────
// ใบพิมพ์ตัด "ม." ออกก่อนอยู่แล้ว แต่บนจอเรียกตรงจาก group_name
eq(classRanges(["ม.3/5", "ม.3/6"]), "3/5-6", "ตัด ม. ให้เองถ้ายังติดมา");

// ── จำกัดจำนวนที่แสดง (ใช้บนจอ ซึ่งชี้เมาส์ดูรายการเต็มได้) ─────────────────
eq(classRanges(["3/1", "3/3", "3/5", "3/7"], 2), "3/1,3 +2",
   "เกินที่กำหนดแล้วบอกจำนวนที่เหลือ");
eq(classRanges(["3/1", "3/3"], 2), "3/1,3", "ไม่เกินก็ไม่ต้องมีหาง");
eq(classRanges(["3/5", "3/6", "3/7", "3/8"], 2), "3/5-8",
   "ยุบแล้วเหลือชิ้นเดียว ไม่ถือว่าเกิน แม้จะมีสี่ห้องเรียน");
eq(classRanges(["3/1", "3/3", "6ข"], 2), "3/1,3 +1",
   "ของที่อ่านไม่ออกนับเป็นหนึ่งชิ้นเหมือนกัน");
eq(classRanges(["3/5", "3/6"], 0), "3/5-6", "max เป็นศูนย์ถือว่าไม่จำกัด");

// ── ไม่ใช่ข้อความ ───────────────────────────────────────────────────────────
// group_name มาจากฐานข้อมูล จึงเป็นค่าว่างหรือ null ได้
eq(classRanges([null as unknown as string, undefined as unknown as string, "3/5"]), "3/5",
   "null กับ undefined ถูกทิ้ง ไม่ทำให้ทั้งช่องพัง");

console.log(`ALL PASS (${n})`);
