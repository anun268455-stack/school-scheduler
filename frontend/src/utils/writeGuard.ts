/**
 * กันไม่ให้การดึงข้อมูลมาทับสิ่งที่เพิ่งแก้
 *
 * ทุกการแก้ในตารางทำแบบมองเห็นผลทันที: ขึ้นจอก่อน แล้วค่อยบอกเซิร์ฟเวอร์
 * ส่วนตัวซิงค์สดก็ดึงข้อมูลของเซิร์ฟเวอร์มาทับเป็นระยะ สองอย่างนี้เคยวิ่งข้าม
 * กันได้ การดึงที่เริ่มก่อนเซิร์ฟเวอร์จะรู้เรื่องการแก้ หรือที่ยังค้างอยู่ตอน
 * มีการแก้ครั้งใหม่ จะเอาตารางเก่ากลับมาทับ โรงเรียนจึงเห็นการเปลี่ยนห้อง
 * เด้งกลับที่เดิมเฉยๆ ไม่มี error ไม่มีอะไรให้กด
 *
 * ต้องนับสองตัว เพราะตอบคนละคำถาม
 *   · busy   — "ตอนนี้ห้ามเริ่มดึง"
 *   · token  — "ระหว่างที่คุณดึงอยู่ มีการแก้เกิดขึ้น คำตอบที่ถืออยู่เก่าแล้ว"
 *     การแก้ที่เริ่มและจบภายในช่วงที่ดึงรอบเดียว จะทำให้ตัวนับแรกกลับเป็นศูนย์
 *     พอดีและรอดไปได้ ถ้าไม่มีตัวที่สอง
 */
export class WriteGuard {
  private inFlight = 0;
  private seq = 0;

  /** จำนวนการแก้ที่เคยเริ่มทั้งหมด — ใช้เป็นตั๋วก่อนเริ่มดึง */
  token(): number {
    return this.seq;
  }

  /** มีการแก้ค้างอยู่ไหม */
  get busy(): boolean {
    return this.inFlight > 0;
  }

  /** คำตอบที่ดึงมาโดยถือตั๋วใบนี้ เก่าไปแล้วหรือยัง */
  stale(askedAt: number): boolean {
    return this.inFlight > 0 || this.seq !== askedAt;
  }

  /**
   * รันการแก้หนึ่งครั้งโดยนับไว้
   *
   * ลดตัวนับใน finally ไม่ใช่หลัง await เพราะถ้าการแก้ล้มเหลวแล้วตัวนับค้าง
   * ระบบจะเชื่อว่ายังแก้ไม่เสร็จตลอดไป แล้วซิงค์สดจะหยุดทำงานถาวร
   */
  async run<T>(fn: () => Promise<T>): Promise<T> {
    this.inFlight += 1;
    this.seq += 1;
    try {
      return await fn();
    } finally {
      this.inFlight = Math.max(0, this.inFlight - 1);
    }
  }
}

/** ตัวเดียวทั้งแอป — การแก้กับการดึงต้องนับจากที่เดียวกันถึงจะกันกันได้ */
export const writeGuard = new WriteGuard();
