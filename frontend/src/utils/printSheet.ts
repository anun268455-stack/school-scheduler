/**
 * printSheet — แบบฟอร์มใบพิมพ์ที่โรงเรียนแก้เองได้
 *
 *   "ช่วยมีระบบที่ก่อนจะปริ้นสามารถกำหนดได้ว่าจะปริ้นอะไรในหน้าอะไรได้ คือถ้าให้
 *    คุณช่วยตั้งแล้วมาแก้ไขต้องให้คุณช่วยเขียนโค้ดทุกรอบ ... พอมีอะไรแก้ไขจะได้
 *    แก้ไขได้เลยไม่ต้องมานั่งเขียนโค้ดใหม่"
 *
 * ของที่อยู่บนใบพิมพ์แล้วแก้ไม่ได้เลย เคยเป็นดังนี้: ข้อความใต้เส้นลงชื่อสองช่อง
 * (เขียนตรึงไว้ในโค้ด) · จำนวนผู้เซ็น (สองคนตายตัว) · ไม่มีวันที่ · ไม่มีเลขหน้า
 * · ไม่มีช่องหมายเหตุ ทุกครั้งที่โรงเรียนอยากเปลี่ยนคำใดคำหนึ่ง ต้องรอให้มีคน
 * มาแก้โค้ดให้
 *
 * ไฟล์นี้เก็บ "แบบฟอร์ม" ไว้เป็นข้อมูล แล้วให้ใบพิมพ์อ่านจากข้อมูลนั้น แบบฟอร์ม
 * ถูกเก็บรวมกับค่าตั้งโรงเรียน (`school_config`) ซึ่งอยู่ในฐานข้อมูลและติดไปกับ
 * การสำรองข้อมูลอยู่แล้ว — ตั้งที่เครื่องหนึ่ง ทุกเครื่องเห็นเหมือนกัน
 *
 * ── กฎข้อแรกของไฟล์นี้ ──
 *
 * ถ้าโรงเรียนยังไม่ได้ตั้งอะไร ใบพิมพ์ต้องออกมาเหมือนเดิมเป๊ะ ๆ ของที่พิมพ์ส่ง
 * เขตไปแล้วทั้งเทอมต้องไม่เปลี่ยนรูปเพราะเราเพิ่มความสามารถให้มัน ค่าตั้งต้น
 * จึงคัดลอกข้อความเดิมมาทุกตัวอักษร และ `undefined` ("ยังไม่ได้ตั้ง") ต้องแยก
 * ออกจาก `[]` ("ตั้งว่าไม่ต้องมีใครเซ็น") ให้ชัด
 */

/**
 * ใบพิมพ์มีสองชนิด และคนเซ็นไม่เหมือนกัน
 *
 *   "อัตรากำลังอยากได้ลายเซ็นแค่รอง ผอ. ส่วนตารางเรียนต้องการลายเซ็นสองคน
 *    ไม่อยากให้เปลี่ยนไปเปลี่ยนมา"
 *
 * ของเดิมมีรายการผู้เซ็นชุดเดียวใช้ร่วมกัน พอจะพิมพ์อีกใบก็ต้องเข้าไปแก้ แล้วแก้
 * กลับตอนพิมพ์ใบแรกอีกครั้ง — ซึ่งนอกจากเสียเวลาแล้วยังพลาดง่าย: ใบที่พิมพ์ด้วย
 * ชุดผู้เซ็นของอีกใบ ดูไม่ออกจนกว่าจะถึงมือคนเซ็น
 */
export type SheetDoc = "timetable" | "workload";

/** ข้อความใต้เส้นลงชื่อของใบตาราง ที่เคยเขียนตรึงไว้ใน PrintView */
export const DEFAULT_SIGNER_ROLES = [
  "รองผู้อำนวยการกลุ่มบริหารวิชาการ",
  "ผู้อำนวยการโรงเรียน",
] as const;

/** ของใบอัตรากำลัง ซึ่งเคยเขียนตรึงไว้คนละที่และคนละคน */
export const DEFAULT_WORKLOAD_SIGNER_ROLES = [
  "หัวหน้ากลุ่มสาระการเรียนรู้",
  "ผู้อำนวยการโรงเรียน",
] as const;

/** มากกว่านี้ใบพิมพ์เสียรูป — เส้นลงชื่อเรียงกันในแถวเดียว */
export const MAX_SIGNERS = 6;

export interface Signer {
  /** ชื่อในวงเล็บใต้เส้น — ว่างได้ จะได้เส้นเปล่าให้เซ็นแล้วเขียนชื่อเอง */
  name: string;
  /** ตำแหน่ง บรรทัดล่างสุด */
  role: string;
  /**
   * ขึ้นบนใบไหนบ้าง — ไม่ระบุ = ทุกใบ
   *
   * "ไม่ระบุ" ต้องแปลว่าทุกใบ ไม่ใช่ไม่ขึ้นเลย เพราะผู้เซ็นที่ตั้งไว้ก่อนมีช่องนี้
   * ย่อมไม่มีค่าในช่องนี้ ถ้าตีความว่าไม่ขึ้น ลายเซ็นที่โรงเรียนตั้งไว้แล้วจะ
   * หายจากใบทั้งหมดพร้อมกันตอนอัปเดต
   */
  on?: SheetDoc[];
}

/**
 * แบบฟอร์มใบพิมพ์หนึ่งชุด
 *
 * ทุกช่องเป็น optional เพราะค่านี้อ่านมาจากก้อน JSON ที่อาจมาจากรุ่นก่อน
 * ที่ยังไม่มีช่องนี้ — "ไม่มีค่า" ต้องหมายถึง "เอาของเดิม" เสมอ
 */
export interface SheetSetup {
  /** ผู้เซ็นทั้งหมด เรียงจากซ้ายไปขวา — undefined = ยังไม่ได้ตั้ง */
  signers?: Signer[];
  /** หมายเหตุท้ายใบ — ว่าง = ไม่พิมพ์ */
  note?: string;
  /** พิมพ์วันที่ที่พิมพ์ใบนี้ */
  showDate?: boolean;
  /** พิมพ์ "หน้า x/y" */
  showPageNumbers?: boolean;
  /**
   * ชื่อเทอมที่กำลังพิมพ์ เช่น "1/2569" — ไม่ได้เก็บกับแบบฟอร์ม ใบพิมพ์ใส่ให้ตอนพิมพ์
   *
   * ต้องเป็นเทอมที่ **กำลังดูอยู่** ไม่ใช่เทอมที่ใช้งานอยู่ (สเปกข้อทดสอบ 17): ปริ้นเทอม
   * เก่าแล้วหัวกระดาษขึ้นชื่อเทอมปัจจุบัน คือใบที่ส่งเขตผิดทั้งปึก ไม่มีค่า = undefined
   * (ไม่เคยสร้างเทอม) และต้องไม่พิมพ์คำว่า "undefined" ลงกระดาษ
   */
  term?: string;
}

const str = (v: unknown): string => (typeof v === "string" ? v : "");

/**
 * ทำให้ค่าที่อ่านมาใช้งานได้ ไม่ว่าจะมาในรูปอะไร
 *
 * ค่านี้อยู่ในก้อน JSON อิสระ จึงเป็นอะไรก็ได้ — ใบพิมพ์ 47 หน้าต้องไม่ล้ม
 * เพราะมีคนเผลอแก้ค่าในฐานข้อมูล หรือเพราะเซิร์ฟเวอร์รุ่นเก่าไม่รู้จักช่องนี้
 */
export function normalizeSheet(raw: unknown): SheetSetup {
  const r = (raw ?? {}) as Record<string, unknown>;
  const out: SheetSetup = {
    note: str(r.note),
    showDate: r.showDate === true,
    showPageNumbers: r.showPageNumbers === true,
  };
  // แบบฟอร์มที่บันทึกไว้ก่อนมีช่องนี้ไม่มี term → คงเป็น undefined (ไม่ใช่ "")
  if (typeof r.term === "string" && r.term.trim()) out.term = r.term.trim();
  if (Array.isArray(r.signers)) {
    out.signers = r.signers
      .filter((s): s is Record<string, unknown> => !!s && typeof s === "object")
      .slice(0, MAX_SIGNERS)
      .map((s) => {
        const signer: Signer = { name: str(s.name), role: str(s.role) };
        if (Array.isArray(s.on)) {
          // เก็บเฉพาะชื่อใบที่รู้จัก — ค่าที่อ่านไม่ออกถูกทิ้ง ไม่ใช่ทำให้ทั้ง
          // แถวหาย ส่วนรายการเปล่าแปลว่า "ทุกใบ" เหมือนไม่ได้ระบุ
          const on = s.on.filter(
            (d): d is SheetDoc => d === "timetable" || d === "workload");
          if (on.length) signer.on = [...new Set(on)];
        }
        return signer;
      });
  }
  return out;
}

/** ชื่อผู้บริหารที่ตั้งไว้ในหน้าตั้งค่า ใช้เป็นค่าตั้งต้นของสองช่องเดิม */
export interface ExecNames {
  deputyName?:   string;
  directorName?: string;
}

/**
 * ผู้เซ็นทั้งหมดสำหรับหน้าแก้ไข — ไม่กรองด้วยชนิดใบ
 *
 * ใช้คู่กับหน้าตั้งค่า ซึ่งต้องเห็นทุกคนเพื่อแก้ ไม่ใช่เห็นเฉพาะคนที่ขึ้นใบใด
 * ใบหนึ่ง — เพราะหน้านั้นบันทึกทั้งรายการกลับลงไป ถ้าเห็นไม่ครบ คนที่ไม่เห็น
 * จะถูกบันทึกทับหายไปเงียบ ๆ ทันทีที่แก้อะไรก็ตามในหน้านั้น
 *
 * ยังไม่ได้ตั้ง = ตั้งต้นด้วยสองช่องของใบตาราง ซึ่งเป็นสิ่งที่หน้านั้นเคยแสดง
 */
export function allSigners(setup: SheetSetup, exec: ExecNames): Signer[] {
  return setup.signers ?? sheetSigners(setup, exec, "timetable");
}

/** ผู้เซ็นคนนี้ขึ้นบนใบชนิดนี้ไหม */
export function signsOn(s: Signer, doc: SheetDoc): boolean {
  // ไม่ระบุ หรือระบุมาเป็นรายการเปล่า = ทุกใบ
  return !s.on || s.on.length === 0 || s.on.includes(doc);
}

/**
 * ผู้เซ็นที่จะพิมพ์ลงใบชนิดนี้
 *
 * ยังไม่ได้ตั้ง = ของเดิมของใบชนิดนั้นทุกตัวอักษร — ซึ่งไม่เหมือนกันสองใบ:
 * ใบตารางเคยเป็น รอง ผอ. + ผอ. ส่วนใบอัตรากำลังเคยเป็น หัวหน้ากลุ่มสาระ + ผอ.
 * (เขียนตรึงไว้คนละไฟล์) โรงเรียนที่ยังไม่เคยเข้าไปตั้งอะไรจึงได้ใบเดิมทั้งคู่
 *
 * ตั้งไว้แล้ว = ตามที่ตั้ง รวมถึง "ตั้งว่าไม่มีใครเซ็น" ซึ่งต้องไม่เด้งกลับเป็น
 * สองช่อง ไม่งั้นการลบผู้เซ็นออกหมดจะทำไม่ได้เลย
 */
export function sheetSigners(
  setup: SheetSetup, exec: ExecNames, doc: SheetDoc = "timetable",
): Signer[] {
  if (setup.signers) return setup.signers.filter((s) => signsOn(s, doc));
  if (doc === "workload") {
    return [
      { name: "", role: DEFAULT_WORKLOAD_SIGNER_ROLES[0] },
      { name: "", role: DEFAULT_WORKLOAD_SIGNER_ROLES[1] },
    ];
  }
  return [
    { name: str(exec.deputyName),   role: DEFAULT_SIGNER_ROLES[0] },
    { name: str(exec.directorName), role: DEFAULT_SIGNER_ROLES[1] },
  ];
}

/**
 * ใส่ค่าจริงลงในข้อความที่โรงเรียนเขียนไว้
 *
 * `{ห้อง}` `{ครู}` `{ภาคเรียน}` `{เทอม}` — `{เทอม}` อ่านจากคีย์ `term` ของ vars
 * (ชื่อเทอมที่กำลังดูอยู่ เช่น 1/2569) ไม่มีค่า = ตัดออกเหมือนตัวแทนค่าอื่น ไม่พิมพ์
 * คำว่า undefined — ตัวแทนค่าที่ไม่รู้จักถูกตัดออกทั้งอัน ไม่ใช่
 * ปล่อยปีกกาติดไปบนกระดาษ เพราะใบที่ส่งเขตแล้วมีคำว่า `{ชั้น}` อยู่กลางหัวเรื่อง
 * คือใบที่ต้องพิมพ์ใหม่ทั้งปึก
 *
 * ช่องว่างที่เหลือจากการตัดถูกยุบ เพื่อไม่ให้ได้ช่องว่างซ้อนกลางประโยค
 */
export function fillTemplate(text: string, vars: Record<string, string>): string {
  return (text ?? "")
    .replace(/\{([^{}]*)\}/g, (_m, key: string) => {
      const k = key.trim();
      return vars[k] ?? (k === "เทอม" ? vars.term : undefined) ?? "";
    })
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

/** ตัวแทนค่าที่ได้จากแบบฟอร์มเอง (ตอนนี้คือชื่อเทอม) ไว้ส่งให้ fillTemplate */
export function sheetVars(setup: SheetSetup): Record<string, string> {
  return setup.term ? { term: setup.term } : {};
}

/**
 * บรรทัดเทอมบนหัวใบพิมพ์ทุกใบ (ตารางเรียน ตารางครู ตารางห้อง ใบอัตรากำลัง)
 *
 * `termName` คือเทอมที่กำลังดูอยู่ ถ้ามีจะชนะค่า term/year ในค่าตั้งโรงเรียนเสมอ
 * ไม่มี (ยังไม่เคยสร้างเทอม) ก็ใช้ของเดิมทุกตัวอักษร และไม่พิมพ์ "undefined"
 */
export function sheetHeading(
  termName: string | undefined,
  cfg: { term?: string; year?: string; schoolName?: string },
): string {
  const name = termName && termName.trim()
    ? termName.trim()
    : `${str(cfg.term)}/${str(cfg.year)}`;
  return `ภาคเรียนที่ ${name}  โรงเรียน${str(cfg.schoolName)}`;
}

/** "หน้า 3/47" — นับจากหนึ่งเพราะคนนับจากหนึ่ง */
export function pageLabel(index: number, total: number): string {
  return `หน้า ${index + 1}/${total}`;
}

const THAI_MONTHS = [
  "มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน",
  "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม",
] as const;

/**
 * วันที่แบบไทย พุทธศักราช
 *
 * ใบที่ส่งเขตใช้ พ.ศ. ไม่ใช่ ค.ศ. — เขียนเองแทนที่จะใช้ตัวจัดรูปแบบของเบราว์เซอร์
 * เพราะผลของตัวนั้นเปลี่ยนตามค่าภาษาของเครื่องที่กดพิมพ์ ซึ่งไม่ควรมีผลกับ
 * เอกสารของโรงเรียน
 */
export function thaiDate(d: Date = new Date()): string {
  return `${d.getDate()} ${THAI_MONTHS[d.getMonth()]} ${d.getFullYear() + 543}`;
}
