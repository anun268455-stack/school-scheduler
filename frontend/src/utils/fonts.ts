/**
 * fonts — ฟอนต์ชุดเดียวที่ครอบทั้งอักษรไทยและอักษรอังกฤษ
 *
 *   "ตอนนี้ตัวอักษร์ มันโดด คือภาษาอังกฤษปกติดี แต่ภาษาไทยขนาดตัวไม่เท่ากัน"
 *
 * รหัสวิชาเขียนปนกันสองชุดอักขระในคำเดียว เช่น ท21102 — ตัว "ท" เป็นอักษรไทย
 * ส่วน "21102" เป็นเลขอารบิก ถ้าฟอนต์ตัวแรกในรายการไม่มีอักษรไทยอยู่ในตัว
 * เบราว์เซอร์จะไปหยิบอักษรไทยจากฟอนต์ตัวถัดไปมาแทนให้เอง ได้เป็นคำเดียวที่
 * มาจากฟอนต์สองตัวคนละสัดส่วน — นั่นคืออาการ "ตัวโดด" ที่เห็น
 *
 * ฉะนั้นฟอนต์ **ทุกตัว** ในรายการต้องมีทั้งไทยและอังกฤษอยู่ในตัวเอง:
 *
 *   Sarabun          โหลดจาก Google Fonts — ตัวหลักที่ตั้งใจให้ใช้
 *   Noto Sans Thai   ติดมากับเครื่อง Android · ChromeOS · ลินุกซ์หลายรุ่น
 *   Leelawadee UI    ติดมากับวินโดวส์ 8 ขึ้นไป
 *   Tahoma           ติดมากับวินโดวส์และแมค สัดส่วนไทย/อังกฤษเท่ากัน
 *
 * ที่ **ห้ามใส่** ในรายการ แม้จะเคยใส่ไว้แล้วก็ตาม:
 *
 *   TH Sarabun New   ตัวอังกฤษเล็กกว่าตัวไทยอย่างเห็นได้ชัด — ตัวนี้อยู่ใน
 *                    ใบพิมพ์มาก่อน และเป็นต้นเหตุที่ทำให้ขนาดไม่เท่ากัน
 *   Arial, Helvetica ไม่มีอักษรไทย ตัวไทยจะหลุดไปฟอนต์อื่นทันที
 *   Inter            ไม่มีอักษรไทย เคยเป็นตัวแรกของทั้งเว็บ
 */

/** ชื่อฟอนต์เรียงตามลำดับที่จะลองใช้ — ต้นฉบับของทั้งเว็บ */
export const FONT_FAMILIES = [
  "Sarabun",
  "Noto Sans Thai",
  "Leelawadee UI",
  "Tahoma",
  "sans-serif",
] as const;

/**
 * รายการฟอนต์ในรูปที่เอาไปใส่ CSS ได้ตรง ๆ
 *
 * ชื่อฟอนต์ครอบอัญประกาศไว้ทุกตัว ยกเว้นคำสามัญของ CSS เช่น sans-serif ที่
 * ห้ามครอบ เพราะถ้าครอบจะกลายเป็นการหาฟอนต์ชื่อ "sans-serif" ซึ่งไม่มีจริง
 */
const CSS_GENERIC = ["sans-serif", "serif", "monospace", "system-ui"];

export const FONT_STACK = FONT_FAMILIES
  .map((f) => (CSS_GENERIC.includes(f) ? f : `"${f}"`))
  .join(",");

/** ฟอนต์ที่ทำให้ขนาดตัวอักษรไม่เท่ากัน — ห้ามโผล่มาในรายการไหนก็ตาม */
export const FONTS_TO_AVOID = [
  "TH Sarabun New",
  "Inter",
  "Arial",
  "Helvetica",
] as const;

/** น้ำหนักตัวอักษรที่ใช้จริงทั้งบนจอและบนใบพิมพ์ */
export const FONT_WEIGHTS = [400, 500, 600, 700] as const;

/**
 * ตัวอย่างข้อความสำหรับสั่งโหลดฟอนต์
 *
 * ใส่ทั้งอักษรไทยและเลข เพราะ Google Fonts แยกไฟล์ฟอนต์เป็นชุดอักขระย่อย
 * ถ้าขอแต่เลข ไฟล์ชุดอักษรไทยก็จะยังไม่ถูกโหลด
 */
export const FONT_SAMPLE = "ท21102 ม.1/1";

/**
 * สระและวรรณยุกต์ไทยที่ลอยอยู่บน-ล่าง ไม่กินความกว้างบรรทัด
 *
 *   U+0E31          ไม้หันอากาศ  ั
 *   U+0E34–U+0E3A   สระ อิ อี อึ อื อุ อู และพินทุ  ิ ี ึ ื ุ ู ฺ
 *   U+0E47–U+0E4E   ไม้ไต่คู้ · วรรณยุกต์ · ทัณฑฆาต · นิคหิต  ็ ่ ้ ๊ ๋ ์ ํ
 *
 * ที่ไม่อยู่ในชุดนี้เพราะกินความกว้างจริง: ะ (U+0E30) · ำ (U+0E33) · สระหน้า
 * เ แ โ ใ ไ (U+0E40–U+0E44)
 */
const THAI_ZERO_WIDTH = /[\u0E31\u0E34-\u0E3A\u0E47-\u0E4E]/g;

/**
 * ความกว้างของข้อความ นับเป็นจำนวนตัวอักษรที่กินที่จริง
 *
 *   "ตอนนี้ตัวอักษร์ มันโดด คือภาษาอังกฤษปกติดี แต่ภาษาไทยขนาดตัวไม่เท่ากัน"
 *
 * ใบพิมพ์ย่อขนาดตัวอักษรของบรรทัดที่ยาวเกินช่อง โดยวัดจากจำนวนตัวอักษร ถ้า
 * นับสระกับวรรณยุกต์ไทยไปด้วย ชื่อไทยจะถูกมองว่ายาวกว่าความจริง เช่น
 * "ห้องประชุมเกียรติยศ" นับได้ 19 ตัวแต่กินที่แค่ 15 — จึงถูกย่อเกินจำเป็น
 * กลายเป็นว่าชื่อไทยพิมพ์ออกมาเล็กกว่าชื่ออังกฤษที่กว้างเท่ากัน
 */
export function displayWidth(text: string): number {
  return (text ?? "").replace(THAI_ZERO_WIDTH, "").length;
}

/**
 * ย่อขนาดตัวอักษรของบรรทัดหนึ่งจนพอดีช่อง
 *
 * ช่องหนึ่งในใบพิมพ์กว้างไม่กี่มิลลิเมตร ข้อความที่ยาวเกินเคยถูกตัดด้วย
 * overflow:hidden บนบรรทัดที่จัดกึ่งกลาง ซึ่งกินทั้งหัวและท้าย —
 * "ห้องประชุมเกียรติยศ" พิมพ์ออกมาเป็น "ประชุมเกียรติ" ซึ่งไม่มีใครตามหาเจอ
 * ย่อลงหนึ่งถึงสองจุดจึงเก็บชื่อไว้ได้ทั้งชื่อ
 *
 * `floor` คือพื้นที่ย่อลงไปได้ลึกสุด เทียบกับขนาดตั้งต้น มีไว้กันไม่ให้ย่อจน
 * อ่านไม่ออก บรรทัดที่อ่านแวบเดียว (รหัสวิชา · เลขห้อง) ตั้งพื้นไว้สูง ส่วน
 * บรรทัดรองอย่างชื่อครูตั้งต่ำกว่าได้ เพราะยอมให้เล็กลงดีกว่าถูกตัดท้ายหาย
 *
 * วัดด้วย displayWidth ไม่ใช่จำนวนตัวอักษร — สระและวรรณยุกต์ไทยไม่กินความกว้าง
 */
export function fitFont(
  text: string, basePt: string, maxChars: number, floor = 0.72,
): string {
  const base = parseFloat(basePt);
  const n = displayWidth(text);
  if (!base || n <= maxChars) return basePt;
  const scaled = base * (maxChars / n);
  return `${Math.max(scaled, base * floor).toFixed(1)}pt`;
}

/** กว้างได้เท่าไรก่อนจะถูกตัดท้ายด้วยจุดไข่ปลา แม้ย่อจนชนพื้นแล้ว */
export const fitsWithin = (maxChars: number, floor = 0.72): number =>
  maxChars / floor;

interface FontLoader {
  load?: (font: string, text?: string) => Promise<unknown>;
}

/**
 * ดึงฟอนต์มาเตรียมไว้ตั้งแต่เปิดเว็บ
 *
 * ใบพิมพ์ถูกซ่อนไว้ (display:none) จนกว่าจะสั่งพิมพ์ และเบราว์เซอร์จะโหลด
 * ไฟล์ฟอนต์เฉพาะตอนมีตัวอักษรให้วาดจริง ๆ ถ้าไม่เตรียมไว้ล่วงหน้า หน้าตัวอย่าง
 * พิมพ์จะถูกวาดด้วยฟอนต์สำรองของเครื่องไปก่อนแล้วค่อยสลับทีหลัง — ซึ่งก็คือ
 * อาการขนาดตัวอักษรไม่เท่ากันบนใบพิมพ์อีกทางหนึ่ง
 *
 * คืนจำนวนคำขอที่ส่งไป เพื่อให้ตรวจสอบได้ว่าทำงานจริง
 */
export function warmUpFonts(doc: Document = document): number {
  const fonts = (doc as unknown as { fonts?: FontLoader }).fonts;
  if (!fonts || typeof fonts.load !== "function") return 0;
  let asked = 0;
  for (const weight of FONT_WEIGHTS) {
    void Promise.resolve(fonts.load(`${weight} 1rem Sarabun`, FONT_SAMPLE))
      .catch(() => undefined);
    asked += 1;
  }
  return asked;
}
