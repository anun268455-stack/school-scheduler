/**
 * serverWake — อยู่กับเซิร์ฟเวอร์ที่หลับเมื่อไม่มีคนใช้
 *
 *   "ตอนนี้เหมือนว่ารอเซิร์ฟเวอร์นานมาก"
 *
 * ตัวจัดตารางอยู่บนเครื่องฟรีที่หลับเมื่อไม่มีใครใช้สิบห้านาที การเปิดหน้าเว็บ
 * ครั้งแรกของวันจึงต้องปลุกเครื่องก่อน ซึ่งกินเวลาเริ่มคอนเทนเนอร์ใหม่ บวกกับ
 * ปลุกฐานข้อมูลอีกชั้น — ระหว่างนั้นทุกคำขอล้มหมด
 *
 * ของเดิมหน้าเว็บรับมือสองอย่างผิดทั้งคู่:
 *
 * ๑. โหลดไม่สำเร็จแล้วเอา "ค่าว่าง" มาใส่แทนแบบเงียบ ๆ (ทุกเส้นมี .catch ที่
 *    คืนค่าเดิมซึ่งตอนเปิดหน้าใหม่คือรายการเปล่า) หน้า "เริ่มสร้างตารางเรียน"
 *    จึงเด้งขึ้นมาเหมือนโรงเรียนไม่มีข้อมูลอะไรเลย — คนเห็นแล้วคิดว่าตารางที่
 *    จัดมาทั้งเทอมหายไปหมด
 *
 * ๒. พอเซิร์ฟเวอร์ตื่นแล้ว ไม่มีใครไปโหลดข้อมูลซ้ำ ซิงค์สดรอบแรกที่สำเร็จแค่
 *    จดเลขรุ่นไว้แล้วจบ จอจึงค้างว่างอยู่อย่างนั้นจนกดรีเฟรชเอง
 *
 * ไฟล์นี้คือตัวตัดสินทั้งสองข้อ แยกออกมาเป็นฟังก์ชันล้วนเพื่อทดสอบได้ตรง ๆ
 * โดยไม่ต้องมีเซิร์ฟเวอร์ ไม่ต้องมีเบราว์เซอร์
 */

/**
 * หน้าเว็บได้ยินเสียงเซิร์ฟเวอร์แล้วหรือยัง
 *
 * "ready" ไม่ได้แปลว่าข้อมูลครบ แปลว่าเซิร์ฟเวอร์ตอบแล้ว — จอว่างหลังจากนี้
 * เป็นคำตอบของเซิร์ฟเวอร์ ไม่ใช่ความเงียบของมัน ซึ่งเป็นเส้นแบ่งที่ทำให้หน้า
 * ตั้งค่าเริ่มต้นขึ้นถูกจังหวะ
 */
export type DataState = "loading" | "ready" | "unreachable";

export interface LoadTally {
  ok: number;
  failed: number;
}

/** นับว่ารอบนี้สำเร็จกี่เส้น ล้มกี่เส้น */
export function tally(results: readonly PromiseSettledResult<unknown>[]): LoadTally {
  let ok = 0, failed = 0;
  for (const r of results) {
    if (r.status === "fulfilled") ok++;
    else failed++;
  }
  return { ok, failed };
}

/**
 * สรุปสถานะจากผลการโหลดหนึ่งรอบ
 *
 * สำเร็จแม้เส้นเดียวก็ถือว่าเซิร์ฟเวอร์ตื่นแล้ว เส้นที่ล้มเป็นเรื่องของเส้นนั้น
 * (เซิร์ฟเวอร์รุ่นเก่าไม่มีเส้นนั้น หรือคำขอเดียวนั้นค้าง) ไม่ใช่ข้อสรุปว่า
 * ทั้งเครื่องยังหลับ ซึ่งแยกสองอย่างนี้ออกจากกันสำคัญ เพราะอย่างหนึ่งต้องรอ
 * อีกอย่างต้องเดินต่อ
 */
export function stateAfter(t: LoadTally): DataState {
  if (t.ok > 0) return "ready";
  if (t.failed > 0) return "unreachable";
  return "loading";                 // ยังไม่ได้ถามอะไรเลย
}

/**
 * หน้า "เริ่มสร้างตารางเรียน" ขึ้นได้ไหม
 *
 * ขึ้นได้ก็ต่อเมื่อเซิร์ฟเวอร์ตอบแล้วว่าไม่มีข้อมูล จอว่างเพราะยังต่อไม่ติด
 * ไม่ใช่โรงเรียนเปล่า และการแสดงหน้านั้นผิดจังหวะไม่ได้แค่ทำให้สับสน — มันชวน
 * ให้คนเริ่มกรอกข้อมูลใหม่ทับของที่ยังอยู่ดี ๆ ในฐานข้อมูล
 */
export function showSetupWizard(data: DataState): boolean {
  return data === "ready";
}

/** จำนวนของที่หน้าเว็บถืออยู่ตอนนี้ */
export interface OnHand {
  groups: number;
  teachers: number;
  slots: number;
}

/**
 * หน้า "กำลังปลุกเซิร์ฟเวอร์" ขึ้นได้ไหม
 *
 * ขึ้นได้ก็ต่อเมื่อไม่มีอะไรจะให้ดูอยู่แล้วจริง ๆ ถ้าเซิร์ฟเวอร์ล่มกลางทางแต่
 * ตารางยังอยู่บนจอ การเอาหน้าสถานะมาบังของจริงคือการพาคนออกจากงานที่เขาทำอยู่
 * เพื่อบอกข่าวที่ป้ายบนแถบเครื่องมือบอกได้อยู่แล้ว — ของที่เห็นอยู่เก่าไปหน่อย
 * ยังมีค่ามากกว่าจอที่ไม่มีอะไรเลย
 */
export function showServerWaking(data: DataState, have: OnHand): boolean {
  if (data === "ready") return false;
  return have.groups === 0 && have.teachers === 0 && have.slots === 0;
}

export type ChipTone = "off" | "waking" | "offline" | "live";

export interface Chip {
  label: string;
  tone: ChipTone;
}

/**
 * ป้ายบอกสถานะบนแถบเครื่องมือ
 *
 * "ออฟไลน์" สีแดงเป็นคำที่ทำให้คนไปงมหาเน็ตของตัวเอง ทั้งที่สิ่งที่เกิดขึ้นคือ
 * เครื่องฟรีกำลังตื่นตามปกติ คำนั้นจึงเหลือไว้เฉพาะกรณีที่มันจริง: มีข้อมูล
 * บนจออยู่แล้วแต่การติดต่อหลุด ของบนจอเริ่มเก่า
 *
 * ยังไม่เคยได้ข้อมูลเลย = "กำลังปลุกเซิร์ฟเวอร์" ซึ่งบอกทั้งว่าเกิดอะไรขึ้น
 * และว่าไม่ต้องทำอะไร รอได้
 */
export function syncChip(
  liveSync: boolean, sync: "connecting" | "live" | "offline", data: DataState,
): Chip {
  if (!liveSync) return { label: "ซิงค์ปิด", tone: "off" };
  if (data === "unreachable") return { label: "กำลังปลุกเซิร์ฟเวอร์", tone: "waking" };
  if (data === "loading") return { label: "กำลังโหลดข้อมูล", tone: "waking" };
  if (sync === "offline") return { label: "ออฟไลน์", tone: "offline" };
  return { label: "ซิงค์สด", tone: "live" };
}
