/**
 * freshLoad — เอาข้อมูลจากเซิร์ฟเวอร์มาทับหน้าจอ เฉพาะเมื่อยังไม่เก่า
 *
 *   "มีบางครั้งเวลาย้ายคาบแล้วเด้งกลับแบบทีหลัง"
 *
 * ตารางทั้งก้อนหนัก 3.3 MB ดาวน์โหลดเป็นวินาที ถ้าระหว่างนั้นมีการย้ายคาบ
 * แล้วคำตอบที่กำลังมาถึงมาทับ สิ่งที่เพิ่งย้ายจะเด้งกลับที่เดิมโดยไม่มีอะไรฟ้อง
 * — ไม่มี error ไม่มีอะไรให้กด คนใช้เห็นแค่คาบที่ย้ายแล้วกลับไปอยู่ที่เก่า
 *
 * ซิงค์สดมีด่านนี้มาตั้งแต่แรก (utils/writeGuard) แต่การโหลดตารางซ้ำหลังการแก้
 * ไม่มี ทั้งที่ถูกเรียกจาก 24 ที่ และที่เรียกบ่อยที่สุดคือการย้ายคาบคู่ซึ่ง
 * โหลดตารางใหม่ทุกครั้ง — คนจัดตารางย้ายคาบติด ๆ กันอยู่แล้ว จังหวะชนกันจึง
 * เกิดได้ตลอด
 *
 * ทิ้งอย่างเดียวไม่พอ เพราะบางที่ต้องการให้ของใหม่ขึ้นจอจริง ๆ (เพิ่งเพิ่มคาบ
 * แล้วคาบต้องโผล่) จึงถามใหม่อีกครั้งหลังการแก้นั้นจบ และยอมแพ้เมื่อครบจำนวน
 * รอบ ปล่อยให้ซิงค์สดตามเก็บทีหลัง ดีกว่าวนไม่จบตอนคนกำลังลากคาบรัว ๆ
 */

/** เท่าที่ตัวนี้ต้องรู้จากด่านกันการเขียน — ประกาศไว้เองเพื่อทดสอบได้ง่าย */
export interface LoadGuard {
  token(): number;
  stale(askedAt: number): boolean;
}

export interface FreshOptions {
  /** ถามใหม่ได้กี่รอบก่อนยอมแพ้ */
  tries?: number;
  /** รออะไรสักครู่ก่อนถามใหม่ — ให้การแก้ที่ค้างอยู่จบก่อน */
  wait?: () => Promise<unknown>;
}

const pause = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * คืน "applied" ถ้าเอาของใหม่มาทับแล้ว หรือ "dropped" ถ้าทิ้งเพราะของเก่าไปแล้ว
 *
 * ข้อผิดพลาดจากการดึงข้อมูลโยนต่อให้คนเรียกจัดการเหมือนเดิม ไม่กลืนเงียบ
 */
export async function loadFresh<T>(
  fetchIt: () => Promise<T>,
  apply: (value: T) => void,
  guard: LoadGuard,
  opts: FreshOptions = {},
): Promise<"applied" | "dropped"> {
  const tries = Math.max(1, opts.tries ?? 2);
  const wait = opts.wait ?? (() => pause(120));
  for (let i = 0; i < tries; i++) {
    const askedAt = guard.token();
    const value = await fetchIt();
    if (!guard.stale(askedAt)) {
      apply(value);
      return "applied";
    }
    if (i < tries - 1) await wait();
  }
  return "dropped";
}
