/**
 * freePeriodLabel — เขียนคำลงในคาบว่างของตารางชั้นเรียน
 *
 *   "ช่วยมีเมนูที่สามารถเลือกได้ว่าคาบว่าง เปลี่ยนเป็นคาบเสริมการเรียนรู้
 *    โดยเหตุผลคือ ตอนนี้อยากให้คาบว่างในคาบที่ 1-8 (ยกเว้นคาบ 9 และคาบ
 *    พักเที่ยง) ให้มีคำว่าเสริมการเรียนรู้"
 *
 * ช่องที่ไม่มีคาบลงอยู่ในใบพิมพ์เคยว่างเปล่า นักเรียนที่ถือตารางไปจึงไม่รู้ว่า
 * ชั่วโมงนั้นต้องทำอะไร โรงเรียนให้เป็นชั่วโมงเสริมการเรียนรู้ ใบพิมพ์จึงควร
 * เขียนไว้ให้เห็น
 *
 * เลขคาบที่ใช้ตรงนี้คือ "เลขคาบที่พิมพ์บนหัวตาราง" ซึ่งนับคาบเรียนกับพักเที่ยง
 * ไล่จากซ้าย ไม่ใช่ period_num ที่เก็บในฐานข้อมูล ของโรงเรียนนี้คาบ 9 คือ
 * 15:20–16:10 ซึ่งเป็นคาบสุดท้ายของวัน และคาบพักเที่ยงเป็นคอลัมน์พักที่ไม่มี
 * ช่องให้เขียนอยู่แล้ว จึงไม่ต้องกันเป็นพิเศษ
 */
import type { TimetableSlot } from "../types";

/** คำที่โรงเรียนใช้ */
export const DEFAULT_FREE_LABEL = "เสริมการเรียนรู้";

/** เขียนถึงคาบที่เท่าไร — คาบ 9 เป็นคาบสุดท้ายของวัน โรงเรียนไม่เอา */
export const DEFAULT_FREE_THROUGH = 8;

/**
 * ช่องนี้นับว่าว่างไหม
 *
 * ว่างจริง ๆ (ไม่มีคาบเลย) หรือมีแต่ "คาบว่างที่จองไว้ให้ว่างตรงกันทั้งกลุ่ม"
 * ซึ่งไม่ใช่คาบเรียน — ทั้งสองแบบพิมพ์ออกมาเป็นช่องเปล่าเหมือนกัน
 */
export function isEmptyCell(slots: readonly TimetableSlot[]): boolean {
  return slots.every((s) => s.is_free_period === true);
}

export interface FreeLabelSetting {
  /** คำที่จะเขียน — ว่าง = ไม่เขียนอะไรเลย */
  label: string;
  /** เขียนเฉพาะคาบที่เลขไม่เกินนี้ */
  through: number;
}

/**
 * คำที่ควรเขียนในช่องนี้ หรือ null ถ้าไม่ต้องเขียนอะไร
 *
 * `printedNo` คือเลขบนหัวตาราง คอลัมน์พักส่งค่า 0 หรือค่าที่ไม่ใช่เลขคาบมา
 * ซึ่งตกเกณฑ์ไปเองโดยไม่ต้องเขียนเงื่อนไขซ้ำ
 */
export function freeCellLabel(
  printedNo: number, slots: readonly TimetableSlot[], s: FreeLabelSetting,
): string | null {
  const text = s.label.trim();
  if (!text) return null;
  if (!Number.isFinite(printedNo) || printedNo < 1 || printedNo > s.through) return null;
  return isEmptyCell(slots) ? text : null;
}
